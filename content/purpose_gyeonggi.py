def _faq_block(pairs):
    """본문용 FAQ dl + FAQPage 스키마(extra_head)."""
    dl = ('<section id="faq"><h2>자주 묻는 질문</h2><dl class="faq-list">'
          + "".join(f"<dt>{q}</dt><dd>{a}</dd>" for q, a in pairs)
          + "</dl></section>")
    schema = {
        "@context": "https://schema.org", "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": q,
             "acceptedAnswer": {"@type": "Answer", "text": a}}
            for q, a in pairs
        ],
    }
    head = ('<script type="application/ld+json">\n'
            + json.dumps(schema, ensure_ascii=False, indent=2) + "\n</script>")
    return dl, head


